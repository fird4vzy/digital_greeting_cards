-- Тяжёлые файлы рукописной открытки — в объектное хранилище, а не в базу.
--
-- До этой колонки у Vercel было жёсткое препятствие: тело запроса ограничено
-- 4,5 МБ, поэтому файл тяжелее лимита загрузить было нельзя ни этой формой, ни
-- какой другой. Из семи существующих работ четыре пролезали целиком, у трёх не
-- проходили видео и звук — то есть открытку, вся суть которой в записи, нельзя
-- было привязать к заказу.
--
-- Путей теперь два, и это не усложнение ради усложнения:
--
--   * `bytes` — как было. Маленькие файлы (вёрстка, стили, скрипт, картинки)
--     ходят одним запросом и лежат в базе. Работает без единой внешней
--     зависимости, поэтому открытка целиком собирается и там, где объектного
--     хранилища нет вовсе — на локальной машине, в предпросмотре.
--   * `url` — для тяжёлых. Браузер грузит файл прямо в хранилище, минуя
--     функцию, и присылает сюда только адрес.
--
-- Поэтому `bytes` перестаёт быть обязательным: у строки заполнено ровно одно
-- из двух. Проверку «ровно одно» ставим здесь, а не полагаемся на код: строка
-- без содержимого и строка с двумя источниками сразу — обе означают, что
-- где-то ошиблись, и лучше узнать об этом при записи.
ALTER TABLE card_files ADD COLUMN IF NOT EXISTS url TEXT;
ALTER TABLE card_files ALTER COLUMN bytes DROP NOT NULL;

ALTER TABLE card_files DROP CONSTRAINT IF EXISTS card_files_one_source;
ALTER TABLE card_files ADD CONSTRAINT card_files_one_source
  CHECK ((bytes IS NULL) <> (url IS NULL));
