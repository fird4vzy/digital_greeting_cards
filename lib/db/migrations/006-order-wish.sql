-- Чего заказчик хочет вместо шаблона.
--
-- До этой колонки выбор шаблона был обязательным по сути, даже когда формально
-- его можно было пропустить: что-то шаблонное показывалось всегда, а заказ
-- приезжал в магазин без единого следа того, что заказчик шаблон не хотел
-- вовсе. Два настоящих случая не имели куда записаться: «у меня своя идея, вот
-- она словами» и «хочу как вот эта ваша работа».
--
-- JSONB, а не две текстовые колонки, потому что это размеченное объединение:
-- либо `{"kind":"own","text":"…"}`, либо `{"kind":"work","workId":"loveis"}`.
-- Две колонки допускали бы состояние, где заполнены обе, — а такого желания
-- не бывает.
--
-- Не в `brief`: там указания магазину — сроки, упаковка, самовывоз. Здесь то,
-- чем должна быть сама открытка. Оператор читает это как разные вещи, и
-- сливать их в одно поле значит потерять различие ровно там, где оно нужно.
--
-- NULL — обычный случай: шаблон выбран или подобран, всё как раньше. Поэтому
-- миграцию можно применить когда угодно: `lib/db/postgres.ts` спрашивает базу
-- один раз за процесс, есть ли колонка, и до этого заказы живут без неё.
ALTER TABLE orders ADD COLUMN IF NOT EXISTS wish JSONB;
