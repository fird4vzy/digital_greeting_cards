-- Открытка, написанная руками, привязанная к заказу.
--
-- До этой таблицы продукт умел ровно одно: собирать открытку движком из
-- шаблона. Настоящий же способ работы — сесть и написать открытку кодом, как
-- сделаны все семь работ в разделе «Наши работы», — не был поддержан вообще:
-- у оператора не было способа привязать свою папку к коду заказа, а значит и
-- к QR на бирке.
--
-- Файлы лежат в базе, а не на диске, потому что у serverless-хостинга диска
-- нет. Прецедент уже есть: фотографии заказов хранятся тут же, внутри JSON,
-- как data-URL.

CREATE TABLE IF NOT EXISTS card_files (
  order_id   TEXT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  -- Путь внутри папки открытки: `index.html`, `assets/song.mp3`. Именно он
  -- делает ссылки внутри чужой вёрстки рабочими без её переписывания.
  path       TEXT NOT NULL,
  media_type TEXT NOT NULL,
  bytes      BYTEA NOT NULL,
  size       INTEGER NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (order_id, path)
);

-- Файл, с которого открытка открывается. Его наличие — единственный признак
-- того, что у заказа есть ручная открытка: пока он пуст, `/c/<код>` показывает
-- сборку движка, как раньше.
ALTER TABLE orders ADD COLUMN IF NOT EXISTS custom_entry TEXT;
