-- Настроений у заказа может быть несколько.
--
-- Колонка `mood` остаётся и остаётся обязательной: по ней подбирается шаблон
-- и её читает движок, которому нужно одно значение, а не список. `moods`
-- хранит весь выбор заказчика целиком, потому что открытку пишет человек, а
-- «смешно и тепло» — это не то же самое, что «смешно», и оператор не должен
-- узнавать об этом из чужого пересказа.
--
-- Порядок в массиве значимый: первым идёт то, что попало в `mood`.

ALTER TABLE orders ADD COLUMN IF NOT EXISTS moods text[] NOT NULL DEFAULT '{}';

-- Уже существующие заказы получают свой единственный выбор в виде списка из
-- одного элемента, чтобы читающему коду не приходилось разбирать два случая.
UPDATE orders
   SET moods = ARRAY[mood]
 WHERE cardinality(moods) = 0
   AND mood <> '';
