-- Ключ, по которому повторно отправленный заказ узнаётся как тот же самый.
--
-- Двойное нажатие на медленной связи в цветочном магазине создавало два
-- заказа, два кода и два сообщения в рабочую группу. Заказчик платил один
-- раз, магазин видел работу на два букета. В форме от этого стоял флаг
-- `publishing`, но он живёт в браузере и не спасает ни от повторной отправки
-- самим браузером, ни от перезагрузки страницы на полпути.
--
-- Ключ выдаёт клиент один раз на черновик и хранит рядом с ним. Значит
-- «тот же заказ» определяется не догадкой по совпадению полей — два похожих
-- заказа подряд бывают, и терять второй нельзя, — а тем, что это буквально
-- одна и та же отправка.
--
-- Индекс частичный: у заказов, принятых до этой миграции, и у тех, что
-- придут без ключа, значение NULL, а NULL в уникальном индексе не конфликтует
-- сам с собой. Так старые строки остаются валидными, а колонка — необязательной.

ALTER TABLE orders ADD COLUMN IF NOT EXISTS idempotency_key TEXT;

CREATE UNIQUE INDEX IF NOT EXISTS orders_idempotency_key_idx
  ON orders (idempotency_key)
  WHERE idempotency_key IS NOT NULL;
