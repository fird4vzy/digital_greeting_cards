/**
 * КАКУЮ БАЗУ БРАТЬ.
 *
 * Одна строчка выбора, вынесенная отдельно, потому что её читают двое —
 * приложение (`lib/db/index.ts`) и скрипт миграций, — и разъехаться им нельзя:
 * миграция, применённая не к той базе, обнаруживается позже всего.
 *
 * **Зачем понадобилось.** `.env.local` появился на домашней машине с боевой
 * строкой подключения, и с этого момента любая проверка формы писала в
 * настоящую базу. Так там и оказался тестовый заказ: прошли форму глазами —
 * получили запись рядом с настоящими. Это не гипотетическая опасность, а уже
 * случившееся; и удалять такое приходится вручную, зная, что искать.
 *
 * **Правило.** Вне продакшена `DATABASE_URL_DEV` побеждает, если задан. В
 * продакшене он не смотрится вообще — иначе переменная, случайно попавшая в
 * Vercel, тихо увела бы боевые заказы в чью-то песочницу.
 *
 * Отдельная переменная, а не отдельный файл, потому что читателей двое и один
 * из них — обычный node-скрипт: он не знает про порядок загрузки Next и про
 * `.env.development.local`. Явное имя работает одинаково везде.
 */

export type DatabaseChoice = {
  url: string | undefined;
  /** Взята ли база разработки. Нужно, чтобы сказать об этом вслух. */
  isDev: boolean;
};

export function databaseChoice(env: NodeJS.ProcessEnv = process.env): DatabaseChoice {
  const production = env.NODE_ENV === 'production';
  const dev = env.DATABASE_URL_DEV?.trim();

  if (!production && dev) return { url: dev, isDev: true };
  return { url: env.DATABASE_URL, isDev: false };
}

/**
 * Говорит один раз за процесс, к какой базе подключились.
 *
 * Молчать нельзя в обе стороны. Работа с боевой базой из локального сервера —
 * то, о чём человек должен знать, набирая тестовое имя в форму. А работа с
 * базой разработки — то, о чём он должен знать, когда «заказ не появился в
 * админке»: он появился, просто в другой базе.
 */
let announced = false;

export function announceDatabase(choice: DatabaseChoice): void {
  if (announced || process.env.NODE_ENV === 'production' || !choice.url) return;
  announced = true;

  console.log(
    choice.isDev
      ? '[db] база разработки (DATABASE_URL_DEV). Боевые данные не затрагиваются.'
      : '[db] ВНИМАНИЕ: используется DATABASE_URL — та же база, что у сайта. ' +
          'Всё, что вы здесь оформите, появится в настоящей админке. ' +
          'Заведите DATABASE_URL_DEV, чтобы проверять на отдельной базе.',
  );
}
