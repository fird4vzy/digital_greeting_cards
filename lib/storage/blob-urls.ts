import type { Order } from '@/lib/db/types';

/**
 * ЧТО МЫ СЧИТАЕМ СВОИМ ФАЙЛОМ.
 *
 * Отдельно от `erase.ts` намеренно. Тот помечен `server-only`, потому что
 * стирает по-настоящему, а `server-only` бросает исключение везде, кроме
 * серверного окружения Next, — то есть и в тестах. Здесь же остались чистые
 * функции без единого побочного действия, и проверять надо именно их: ошибка
 * стоит дорого в обе стороны.
 *
 * Признать своим чужой адрес — значит по чьей-то просьбе пойти удалять что-то
 * на постороннем хосте. Не признать свой — оставить чужие фотографии лежать по
 * публичной ссылке после того, как человек попросил их убрать.
 *
 * Тот же вопрос задаётся ещё в одном месте: при приёме адреса загруженного
 * файла в `app/api/admin/card-files/route.ts`. Там он мешает `/u/<код>` стать
 * открытым прокси.
 */

/** Хост объектного хранилища. */
const BLOB_HOST = '.blob.vercel-storage.com';

export function isStoredBlob(url: string): boolean {
  try {
    const parsed = new URL(url);
    return parsed.protocol === 'https:' && parsed.hostname.endsWith(BLOB_HOST);
  } catch {
    // Не адрес вовсе — например, `data:`-URL старого заказа. Не наш файл, и
    // это не ошибка: до переезда снимки лежали прямо в строке.
    return false;
  }
}

/**
 * Все адреса, которые заказ оставил в хранилище.
 *
 * Фотографии живут в самом заказе; файлы рукописной открытки — в `card_files`,
 * поэтому их список передаётся отдельно: так функция не ходит в базу и её
 * можно звать и из действия админки, и из будущей уборки по сроку хранения.
 *
 * **Адреса собираются из данных, а не перечисляются по префиксу пути.**
 * Спросить хранилище «что лежит под `cards/<id>/`» было бы проще, но это
 * значило бы доверять форме пути: она однажды изменится, и стирание молча
 * начнёт промахиваться.
 */
export function blobUrlsOf(order: Pick<Order, 'photos'>, cardFileUrls: string[] = []): string[] {
  return [...order.photos.map((photo) => photo.url), ...cardFileUrls].filter(isStoredBlob);
}
