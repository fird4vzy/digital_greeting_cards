import 'server-only';
import { cookies } from 'next/headers';
import { ADMIN_SESSION_COOKIE, verifyAdminSession } from '@/lib/auth/admin';

/**
 * Проверка сессии для обработчиков маршрутов.
 *
 * **Почему это отдельный файл, а не три строки в каждом маршруте.** Посредник
 * в `proxy.ts` намеренно не трогает `/api/` — матчер исключает его первым же
 * правилом, — и настоящая граница проходит внутри каждого обработчика. Пока
 * каждый вспоминал о ней сам, четыре маршрута из девяти не вспомнили, и это
 * не разгильдяйство, а свойство схемы: пропуск ничем не отличался от честного
 * публичного маршрута, ни в типах, ни на глаз при чтении диффа.
 *
 * Аудит 28 августа нашёл цену этого: `GET /api/orders` без единой проверки
 * отдавал весь список заказов — имена, телефоны, телеграмы, приватные письма
 * и фотографии, — а `PATCH /api/orders/[id]` позволял кому угодно опубликовать
 * или переписать чужую открытку. Оба лежали в одном репозитории с админкой,
 * которая проверяет сессию на пяти уровнях.
 *
 * Одна функция всего этого не чинит — забыть строку можно и с ней. Но теперь
 * забытая строка выглядит как пропуск: у соседних маршрутов она есть, и в
 * `grep -L adminOnly app/api` её отсутствие видно списком.
 */
export async function hasAdminSession(): Promise<boolean> {
  return verifyAdminSession((await cookies()).get(ADMIN_SESSION_COOKIE)?.value);
}

/**
 * Для обработчиков маршрутов: `null` — пускать, иначе готовый ответ.
 *
 * Ровно «не аутентифицирован» и ничего больше: отвечать «нет такого заказа»
 * или «нет прав» значит рассказать анониму, что заказ существует.
 */
export async function adminOnly(): Promise<Response | null> {
  if (await hasAdminSession()) return null;
  return Response.json({ error: 'Not authenticated' }, { status: 401 });
}

/**
 * Для серверных действий, которые ничего не возвращают наружу.
 *
 * Бросает, а не возвращает: действие без прав не должно доехать до строки,
 * которая что-то меняет, а `if` можно забыть проверить.
 *
 * Серверное действие — это POST-эндпоинт, до которого можно достучаться,
 * зная его идентификатор, ни разу не открыв страницу, где он живёт. Поэтому
 * проверка в разметке страницы не значит ничего, и каждое действие обязано
 * спрашивать само.
 */
export async function requireAdmin(): Promise<void> {
  if (!(await hasAdminSession())) throw new Error('Not authenticated');
}
