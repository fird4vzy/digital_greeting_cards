import { forwardIncoming } from '@/lib/notify/telegram';

/**
 * Входящие сообщения боту — в рабочую группу.
 *
 * До этого маршрута бот умел только отправлять: флорист, нажавший кнопку на
 * `/shops`, писал в пустоту. Ссылка выглядела рабочей, ответа не было — хуже,
 * чем неработающая.
 *
 * **Почему вебхук, а не опрос.** Опрос требует живого процесса, а здесь
 * serverless: держать его негде. Вебхук — единственная форма, в которой
 * приём сообщений вообще возможен на этом хостинге.
 *
 * **Защита — заголовком, а не догадкой.** Адрес вебхука знает только тот, кто
 * его зарегистрировал, но полагаться на это нельзя: адрес попадёт в логи, в
 * историю команд, в чей-нибудь скриншот. Telegram умеет присылать
 * `secret_token` в заголовке каждого запроса, и без совпадения с
 * `TELEGRAM_WEBHOOK_SECRET` маршрут отвечает 401 и ничего не делает.
 *
 * **Всегда 200, кроме неверного секрета.** Telegram считает любой не-2xx
 * ошибкой доставки и повторяет запрос, наращивая паузы; на ошибке в разборе
 * это превратилось бы в бесконечный поток одного и того же сообщения. Всё,
 * что не прошло, тихо проглатывается — так же, как `notifyNewOrder` глотает
 * сбой отправки, чтобы не уронить заказ.
 */

export async function POST(request: Request) {
  const secret = process.env.TELEGRAM_WEBHOOK_SECRET;

  // Без секрета маршрут выключен целиком. Открытый вебхук — это возможность
  // для любого прохожего слать в рабочую группу что угодно от имени бота.
  if (!secret) return new Response('Not found', { status: 404 });

  if (request.headers.get('x-telegram-bot-api-secret-token') !== secret) {
    return new Response('Unauthorized', { status: 401 });
  }

  try {
    await forwardIncoming(await request.json());
  } catch {
    // Разбор упал или Telegram недоступен. Молча: см. про повторы выше.
  }

  return new Response('ok');
}
