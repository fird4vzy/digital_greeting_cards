import { handleUpload, type HandleUploadBody } from '@vercel/blob/client';
import { RATE_LIMITS, rateLimit, tooManyRequests } from '@/lib/security/rate-limit';

/**
 * ВЫДАЁТ ТОКЕН НА ЗАГРУЗКУ ФОТОГРАФИИ — И БОЛЬШЕ НИЧЕГО.
 *
 * Байты снимка сюда не приходят. Браузер просит у этого маршрута короткий
 * подписанный токен и грузит файл прямо в хранилище, минуя функцию. Ради этого
 * всё и затевалось: у Vercel тело запроса ограничено 4,5 МБ, и до сих пор
 * фотографии ехали вместе с заказом внутри него — шесть снимков с телефона в
 * это окно не помещались, а те, что помещались, потом лежали base64 прямо в
 * строке заказа и раздували каждое чтение книги заказов.
 *
 * **Маршрут открытый, и это не недосмотр.** Заказ оформляет человек с улицы,
 * входа у него нет и быть не должно. Значит, единственное, что отделяет форму
 * от бесплатного файлохранилища для посторонних, — рамки, заданные здесь:
 *
 *   - только изображения, и только три формата, которые мы сами и создаём;
 *   - потолок размера — браузер ужимает снимок до 1600 px по длинной стороне,
 *     это 200–400 КБ, поэтому пять мегабайт уже с большим запасом;
 *   - ограничение частоты по адресу.
 *
 * Снять любую из трёх — значит открыть чужим людям бесплатный хостинг за свой
 * счёт.
 *
 * **Без `BLOB_READ_WRITE_TOKEN` маршрут честно отвечает 501.** Не 500 и не
 * тишина: клиент по этому коду понимает, что хранилище не подключено, и
 * возвращается к прежнему способу — data-URL внутри заказа. Так продукт
 * работает и до того, как хранилище включат в панели Vercel, и сразу после,
 * без правки кода.
 */

/** Пять мегабайт: ужатый снимок — 200–400 КБ, так что это запас, а не норма. */
const MAX_BYTES = 5_000_000;

export async function POST(request: Request): Promise<Response> {
  if (!process.env.BLOB_READ_WRITE_TOKEN) {
    return Response.json(
      { error: 'Blob storage is not configured' },
      { status: 501 },
    );
  }

  const attempt = await rateLimit(RATE_LIMITS.photoUpload);
  if (!attempt.ok) return tooManyRequests(attempt);

  const body = (await request.json().catch(() => null)) as HandleUploadBody | null;
  if (!body) return Response.json({ error: 'Invalid request' }, { status: 400 });

  try {
    const result = await handleUpload({
      body,
      request,
      onBeforeGenerateToken: async () => ({
        allowedContentTypes: ['image/jpeg', 'image/png', 'image/webp'],
        maximumSizeInBytes: MAX_BYTES,
        // Имя файла приходит от браузера. Со случайным хвостом чужое имя не
        // может перезаписать уже загруженный снимок и не может угадываться.
        addRandomSuffix: true,
      }),
      // Обязателен по контракту, но делать здесь нечего: адрес снимка
      // возвращается браузеру и уезжает в заказ вместе с остальными ответами.
      // На localhost этот вызов вообще не происходит — хранилищу некуда
      // достучаться, — и полагаться на него поэтому нельзя.
      onUploadCompleted: async () => {},
    });

    return Response.json(result);
  } catch (error) {
    // Сюда попадают отказы самого хранилища: неподходящий тип, превышенный
    // размер, протухший токен. Текст отдаём как есть — он адресован разработке,
    // а заказчик увидит запасной путь, а не эту строку.
    return Response.json({ error: (error as Error).message }, { status: 400 });
  }
}
