import { NextResponse } from 'next/server';
import { storeHealth } from '@/lib/db';

/**
 * GET /api/health — жив ли путь до базы.
 *
 * **Зачем.** Самая опасная поломка этого приложения тихая: база недоступна,
 * заказы принимаются, заказчик видит «готово», а записи нигде нет. Теперь
 * такое падает громко (`lib/db/index.ts`), но падает оно на том, кто в этот
 * момент оформлял заказ. Этот маршрут — способ узнать раньше него.
 *
 * Проверка настоящая: запрос в базу, а не чтение переменных окружения.
 * `DATABASE_URL` может быть задан и вести в никуда — именно этот случай и
 * надо ловить.
 *
 * Открыт без сессии: мониторинг ходит сюда без куки. Наружу отдаются только
 * «да/нет» и какое хранилище активно — ни строки подключения, ни текста
 * ошибки, в котором может оказаться хост с паролем. Текст уходит в лог.
 *
 * 503, а не 200 с телом `{ok:false}`: пингеры смотрят на код ответа, и
 * здоровым двухсотым такая проверка была бы бесполезна.
 */
export const dynamic = 'force-dynamic';

export async function GET() {
  const health = await storeHealth();

  if (!health.ok) {
    console.error(`[health] хранилище недоступно: ${health.error}`);
  }

  return NextResponse.json(
    { ok: health.ok, store: health.store },
    {
      status: health.ok ? 200 : 503,
      headers: { 'Cache-Control': 'no-store' },
    },
  );
}
