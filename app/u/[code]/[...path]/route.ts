import { getCardFileStore, getOrderByCode } from '@/lib/db';

/**
 * Отдаёт файлы открытки, написанной руками.
 *
 * Отдельный путь `/u/…`, а не `/c/<код>/…`: так чужие файлы отделены от
 * страницы открытки и адресом, и правилами отдачи.
 *
 * **Непрозрачный origin даёт не путь, а песочница.** Раньше комментарий здесь
 * утверждал обратное, и это была ошибка с последствиями: путь к origin
 * отношения не имеет, `/u/index.html` — обычная ссылка на том же домене, и
 * при прямом переходе по ней — а оператор переходит, он же проверяет
 * загруженную работу — чужой скрипт выполнялся на birdunyo.uz вообще без
 * песочницы. Атрибут `sandbox` у фрейма на прямой переход не действует.
 * Кука оператора `httpOnly`, читать её скрипт не мог, но ему и не нужно:
 * `SameSite=Lax` отправляет её сама, и `fetch('/admin/export')` из такой
 * страницы забирал всю книгу заказов.
 *
 * Поэтому песочница объявляется заголовком, на самом ответе: он действует
 * всегда — и во фрейме, и при прямом переходе. Директива `sandbox` в CSP
 * умеет то, чего не умеет атрибут.
 *
 * **Дыра закрыта не до конца.** Полное решение — отдавать `/u/` с другого
 * хоста, тогда origin чужой по-настоящему и вопрос снимается вместе с
 * доверием к заголовкам. Это требует поддомена и записи в DNS. До тех пор
 * песочница снимает главное: скрипт теряет права своего происхождения.
 *
 * Функция `importFromRepository` в `app/admin/templates/actions.ts` делает
 * это не теорией: она существует ровно затем, чтобы брать чужой рукописный
 * HTML из произвольных репозиториев на GitHub.
 *
 * **Доступ.** Файлы отдаются для любого неотменённого заказа, а не только для
 * опубликованного, — тем же доводом, что и черновик открытки: код угадать
 * нельзя, а оператору надо посмотреть работу до публикации. Публичный смысл
 * при этом сохраняет `/c/<код>`: он остаётся строго для опубликованных.
 *
 * Заголовок `Access-Control-Allow-Origin` обязателен и не является
 * послаблением: фрейм с непрозрачным origin запрашивает шрифты как
 * межсайтовые, и без заголовка чужая вёрстка тихо рисуется не тем шрифтом.
 * Ровно та же причина, что и в разделе «Наши работы».
 */

type Params = { params: Promise<{ code: string; path: string[] }> };

export async function GET(_request: Request, { params }: Params) {
  const { code, path } = await params;

  const order = await getOrderByCode(code);
  if (!order || order.status === 'CANCELLED') {
    return new Response('Not found', { status: 404 });
  }

  const store = await getCardFileStore();
  const file = await store.read(order.id, path.join('/'));
  if (!file) return new Response('Not found', { status: 404 });

  return new Response(new Uint8Array(file.bytes), {
    headers: {
      'Content-Type': file.mediaType,
      'Content-Length': String(file.bytes.length),
      'Access-Control-Allow-Origin': '*',
      // Песочница на уровне документа. `allow-scripts` — потому что открытки
      // анимированы и без скриптов мертвы; `allow-popups` — потому что ссылка
      // в открытке должна открываться. `allow-same-origin` не появится здесь
      // никогда: вместе с `allow-scripts` эта пара отменяет песочницу целиком,
      // и мы вернулись бы ровно туда, откуда ушли.
      'Content-Security-Policy': 'sandbox allow-scripts allow-popups',
      // Открытка живёт по постоянному адресу, но оператор её переписывает,
      // пока заказ в работе. Поэтому кеш короткий и с проверкой, а не годовой.
      'Cache-Control': 'public, max-age=60, must-revalidate',
      // Тип берётся из расширения при загрузке; браузеру не надо его угадывать.
      'X-Content-Type-Options': 'nosniff',
    },
  });
}
