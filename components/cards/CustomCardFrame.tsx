/**
 * Открытка, написанную которую оператор загрузил сам.
 *
 * Показывается вместо сборки движка, когда у заказа есть `customEntry`.
 *
 * **Почему во фрейме, а не прямо на странице.** Это чужой HTML со своим
 * скриптом, а `/c/<код>` делит origin с админкой. Отдать его как есть значит
 * позволить скрипту прочитать сессионную куку оператора — это то самое
 * возражение, из-за которого проект когда-то отказался принимать сторонний
 * HTML. Фрейм с `sandbox="allow-scripts"` и **без** `allow-same-origin` даёт
 * документу непрозрачный origin: он не видит куки этого домена и не достаёт
 * DOM родителя. Пара этих флагов вместе отменяет песочницу, поэтому второго
 * здесь нет и быть не должно.
 *
 * `allow-popups` и `allow-popups-to-escape-sandbox` — потому что в открытках
 * встречаются ссылки наружу, и без них нажатие не делает ничего. Тот же набор,
 * что у раздела «Наши работы».
 *
 * `allow="autoplay"` здесь, в отличие от галереи, выставлен: человек открыл
 * одну конкретную открытку, и звук с видео — часть того, что ему прислали.
 */
export function CustomCardFrame({
  src,
  title,
}: {
  /** Адрес входного файла в `/u/<код>/…`. */
  src: string;
  title: string;
}) {
  return (
    <iframe
      src={src}
      title={title}
      sandbox="allow-scripts allow-popups allow-popups-to-escape-sandbox"
      allow="autoplay; fullscreen"
      className="h-[100svh] w-full border-0"
    />
  );
}
